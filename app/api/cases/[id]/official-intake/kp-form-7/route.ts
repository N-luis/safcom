import { NextRequest } from 'next/server';
import { prisma } from '@/lib/prisma';
import { requireAuth, errorResponse } from '@/lib/auth';
import { loadActor, isVawcType } from '@/lib/reporterAccess';
import { decideIntakeAccess, loadIntakeCase, logIntakeAccess } from '@/lib/officialIntake';
import { formForType, upgradeResponses } from '@/lib/intakeForms';
import { loadHearingCase, eligibilityOf, noStore } from '@/lib/hearingsServer';
import { kpForm7Content, kpForm7Missing } from '@/lib/kpForm7';
import { buildKpForm7Pdf } from '@/lib/kpForm7Pdf';
import { BARANGAY_CONTEXT } from '@/lib/safecommConfig';
import { VAWC_HEARING_REFUSAL } from '@/lib/hearings';
import type { Responses } from '@/lib/officialIntakeForm';

/**
 * KP Form No. 7 (Complainant's Form) for a blotter case, as a PDF.
 *
 * Only for a case an official has found eligible for Katarungang Pambarangay
 * proceedings - verified category and a recorded eligibility review - and
 * never a VAWC case (RA 9262). A blotter intake does not become a KP
 * complaint by itself: this is asked for, and every request is logged.
 * Access is the intake's own: whoever may view the blotter intake.
 */
export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const auth = await requireAuth(req);
  if ('status' in auth) return auth;
  try {
    const actor = await loadActor(auth.user.userId);
    if (!actor) return errorResponse('Unauthorized', 401);
    const c = await loadIntakeCase(id);
    const log = (outcome: 'permitted' | 'denied', code: string) =>
      logIntakeAccess({ actorId: actor.id, actorRole: actor.role, caseId: id, caseNumber: c?.caseNumber, outcome, code: `kp_form7:${code}` });
    if (!c) { await log('denied', 'not_found'); return errorResponse('Case not found', 404); }
    const access = decideIntakeAccess(actor, c);
    if (access.hidden) { await log('denied', access.code); return errorResponse('Case not found', 404); }
    if (!access.view) { await log('denied', access.code); return errorResponse(access.message ?? 'Not permitted', 403); }
    if (isVawcType(c.caseType)) { await log('denied', 'vawc'); return errorResponse(VAWC_HEARING_REFUSAL, 422); }
    const intake = c.officialIntake;
    if (!intake || formForType(intake.formType).type !== 'BLOTTER_REPORT') { await log('denied', 'no_intake'); return errorResponse('Start the Blotter Intake Form first - KP Form No. 7 is drawn from it.', 404); }

    const hc = await loadHearingCase(id);
    const eligibility = hc ? await eligibilityOf(hc) : null;
    if (!eligibility?.eligible) {
      await log('denied', 'not_eligible');
      return noStore({ success: false, error: `KP Form No. 7 is for cases found eligible for Katarungang Pambarangay proceedings. ${eligibility?.reasons[0] ?? ''}`.trim(),
        reasons: eligibility?.reasons ?? [] }, 422);
    }
    const responses = upgradeResponses(formForType(intake.formType), intake.responses as Responses);
    const content = kpForm7Content(responses, { caseNumber: c.caseNumber, barangay: BARANGAY_CONTEXT.name, municipality: c.municipality, province: c.province });
    const missing = kpForm7Missing(content);
    if (missing.length) { await log('denied', 'incomplete'); return noStore({ success: false, error: `Add ${missing.join('; ')} first.`, missing }, 422); }

    const bytes = await buildKpForm7Pdf(content, { draft: intake.status !== 'COMPLETED' });
    const me = await prisma.user.findUnique({ where: { id: actor.id }, select: { name: true } });
    await prisma.activity.create({ data: {
      type: 'intake', message: `KP Form No. 7 (Complainant's Form) generated by ${me?.name ?? 'an official'}`,
      entityId: intake.id, entityType: 'OfficialIntake', userId: actor.id, caseId: id, color: '#0369a1',
    } });
    await log('permitted', access.code);
    return new Response(Buffer.from(bytes), { headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="KP-Form-7-${c.caseNumber.replace(/[^A-Za-z0-9-]/g, '_')}.pdf"`,
      'Cache-Control': 'no-store, private', 'X-Content-Type-Options': 'nosniff',
    } });
  } catch {
    return errorResponse('KP Form No. 7 could not be produced right now.', 503);
  }
}
