import { NextRequest } from 'next/server';
import { z } from 'zod';
import { prisma } from '@/lib/prisma';
import { errorResponse } from '@/lib/auth';
import { gateCaseRecords, noStore } from '@/lib/caseRecordsServer';
import { letterNumberFor, ISSUE_METHODS, type IssueMethod } from '@/lib/analytics';
import { ANONYMOUS_NAME } from '@/lib/interviewTypes';

/**
 * The acknowledgement letter for one case - it confirms receipt only.
 *
 *   GET   - the letter, if there is one.
 *   POST  - generate it. One per case: a second request returns the first.
 *   PATCH - record that it was issued to the reporter, and how.
 *
 * The recipient is fixed at generation: the reporter's name, or "The
 * Reporter" for an anonymous report, whose name officials never see.
 */

type Params = { params: Promise<{ id: string }> };

async function shape(caseId: string) {
  const l = await prisma.acknowledgementLetter.findUnique({ where: { caseId } });
  if (!l) return null;
  const ids = [l.generatedById, l.issuedById].filter((x): x is string => Boolean(x));
  const users = await prisma.user.findMany({ where: { id: { in: ids } }, select: { id: true, name: true } });
  const name = (id: string | null) => (id && users.find(u => u.id === id)?.name) || null;
  return { ...l, generatedBy: name(l.generatedById), issuedBy: name(l.issuedById) };
}

export async function GET(req: NextRequest, { params }: Params) {
  const { id } = await params;
  const g = await gateCaseRecords(req, id, 'view', 'acknowledgement');
  if ('error' in g) return g.error;
  try {
    return noStore({ success: true, data: { letter: await shape(id), canEdit: g.access.edit } });
  } catch {
    return errorResponse('The letter could not be loaded right now.', 503);
  }
}

export async function POST(req: NextRequest, { params }: Params) {
  const { id } = await params;
  const g = await gateCaseRecords(req, id, 'edit', 'acknowledgement');
  if ('error' in g) return g.error;
  try {
    const existing = await prisma.acknowledgementLetter.findUnique({ where: { caseId: id } });
    if (existing) return noStore({ success: true, data: { letter: await shape(id), created: false } });
    const c = await prisma.case.findUnique({ where: { id }, select: { caseNumber: true, residentName: true, reporterIdentityWithheld: true } });
    if (!c) return errorResponse('Case not found', 404);
    const anonymous = c.reporterIdentityWithheld || c.residentName === ANONYMOUS_NAME;
    const me = await prisma.user.findUnique({ where: { id: g.actor.id }, select: { name: true } });
    try {
      await prisma.$transaction(async tx => {
        await tx.acknowledgementLetter.create({ data: {
          caseId: id, letterNumber: letterNumberFor(c.caseNumber),
          recipient: anonymous ? 'The Reporter' : c.residentName, generatedById: g.actor.id,
        } });
        await tx.activity.create({ data: {
          type: 'acknowledgement', message: `Acknowledgement letter generated by ${me?.name ?? 'an official'}`,
          entityId: id, entityType: 'Case', userId: g.actor.id, caseId: id, color: '#0f766e',
        } });
      });
    } catch (e) {
      // Two clicks at once: the unique case id lets one through; the other gets it.
      if (!(e instanceof Error && /Unique constraint|P2002/.test(e.message))) throw e;
    }
    await g.log('permitted', g.access.code);
    return noStore({ success: true, data: { letter: await shape(id), created: true } }, 201);
  } catch {
    return errorResponse('The letter could not be generated right now.', 503);
  }
}

const issueSchema = z.object({
  issueMethod: z.enum(Object.keys(ISSUE_METHODS) as [IssueMethod, ...IssueMethod[]]),
});

export async function PATCH(req: NextRequest, { params }: Params) {
  const { id } = await params;
  const g = await gateCaseRecords(req, id, 'edit', 'acknowledgement');
  if ('error' in g) return g.error;
  const parsed = issueSchema.safeParse(await req.json().catch(() => null));
  if (!parsed.success) return errorResponse('Say how the letter was given to the reporter', 400);
  try {
    const l = await prisma.acknowledgementLetter.findUnique({ where: { caseId: id } });
    if (!l) return errorResponse('Generate the letter first', 404);
    if (l.status === 'ISSUED') return noStore({ success: true, data: { letter: await shape(id), changed: false } });
    const me = await prisma.user.findUnique({ where: { id: g.actor.id }, select: { name: true } });
    await prisma.$transaction(async tx => {
      // Only from GENERATED, so a second "issued" never moves the date.
      const done = await tx.acknowledgementLetter.updateMany({
        where: { id: l.id, status: 'GENERATED' },
        data: { status: 'ISSUED', issuedAt: new Date(), issuedById: g.actor.id, issueMethod: parsed.data.issueMethod },
      });
      if (done.count) {
        await tx.activity.create({ data: {
          type: 'acknowledgement', message: `Acknowledgement letter issued by ${me?.name ?? 'an official'} (${ISSUE_METHODS[parsed.data.issueMethod].toLowerCase()})`,
          entityId: id, entityType: 'Case', userId: g.actor.id, caseId: id, color: '#0f766e',
        } });
      }
    });
    await g.log('permitted', g.access.code);
    return noStore({ success: true, data: { letter: await shape(id), changed: true } });
  } catch {
    return errorResponse('The letter could not be updated right now.', 503);
  }
}
