import { PDFDocument, StandardFonts, rgb, type PDFFont } from 'pdf-lib';

/**
 * The acknowledgement letter: the barangay received a report, on this date,
 * under this reference number - and nothing more.
 *
 * It is not a finding, a summons, a certification or a protection order, and
 * it says so. On a VAWC case it does not name the category or the desk: a
 * letter can be found and read by the person the report is about.
 */

export interface LetterInput {
  letterNumber: string;
  caseNumber: string;
  recipient: string;
  receivedAt: Date;
  generatedAt: Date;
  preparedBy: string | null;
  /** Shown on blotter letters only. */
  category: string | null;
  barangay: string;
  municipality: string;
  province: string;
  status: 'GENERATED' | 'ISSUED';
  issuedAt: Date | null;
}

const W = 612, H = 792, M = 64;
const CW = W - 2 * M;
const NAVY = rgb(0.05, 0.12, 0.27), GRAY = rgb(0.35, 0.35, 0.35);
const fmt = (d: Date) => d.toLocaleDateString('en-PH', { timeZone: 'Asia/Manila', year: 'numeric', month: 'long', day: 'numeric' });

export async function buildAcknowledgementPdf(input: LetterInput): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`Acknowledgement of Receipt - ${input.letterNumber}`);
  pdf.setProducer('SafeComm');
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const italic = await pdf.embedFont(StandardFonts.HelveticaOblique);
  const page = pdf.addPage([W, H]);

  // Only characters the standard fonts can print; anything else becomes "?".
  const clean = (s: string) => [...s].map(ch => { try { font.encodeText(ch); return ch; } catch { return '?'; } }).join('');
  const wrap = (s: string, f: PDFFont, size: number, width: number) => {
    const out: string[] = [];
    for (const para of clean(s).split('\n')) {
      let line = '';
      for (const word of para.split(/ +/)) {
        const t = line ? `${line} ${word}` : word;
        if (f.widthOfTextAtSize(t, size) <= width) { line = t; continue; }
        if (line) out.push(line);
        line = word;
      }
      out.push(line);
    }
    return out;
  };
  let y = H - M;
  const center = (s: string, f: PDFFont, size: number, color = NAVY) => {
    const t = clean(s);
    page.drawText(t, { x: (W - f.widthOfTextAtSize(t, size)) / 2, y, size, font: f, color });
    y -= size + 4;
  };
  const para = (s: string, f: PDFFont = font, size = 11, gap = 10) => {
    for (const l of wrap(s, f, size, CW)) { page.drawText(l, { x: M, y, size, font: f, color: rgb(0, 0, 0) }); y -= size + 5; }
    y -= gap;
  };

  center('Republic of the Philippines', font, 10, GRAY);
  center(`Province of ${input.province}`, font, 10, GRAY);
  center(`Municipality of ${input.municipality}`, font, 10, GRAY);
  center(`BARANGAY ${input.barangay.toUpperCase()}`, bold, 13);
  y -= 6;
  page.drawLine({ start: { x: M, y }, end: { x: W - M, y }, thickness: 1, color: NAVY });
  y -= 30;
  center('ACKNOWLEDGEMENT OF RECEIPT', bold, 15);
  y -= 14;

  page.drawText(clean(`Letter No.: ${input.letterNumber}`), { x: M, y, size: 10, font: bold, color: NAVY });
  const dateText = clean(`Date: ${fmt(input.generatedAt)}`);
  page.drawText(dateText, { x: W - M - font.widthOfTextAtSize(dateText, 10), y, size: 10, font, color: rgb(0, 0, 0) });
  y -= 30;

  para(`To: ${input.recipient}`, bold, 11, 14);
  para(`This acknowledges that the barangay received your report on ${fmt(input.receivedAt)}. It is recorded under reference number ${input.caseNumber}.`);
  if (input.category) para(`Category recorded at filing (preliminary, subject to review): ${input.category}.`);
  para('Please keep this reference number. You can use it to follow up on your report at the barangay hall or through SafeComm.');
  para('This letter confirms receipt only. It is not a finding on what was reported, it does not decide anyone\'s responsibility, and it is not a summons, a certification, a clearance or a protection order.', italic, 10.5, 30);

  // Signature block
  y -= 20;
  page.drawLine({ start: { x: M, y }, end: { x: M + 220, y }, thickness: 0.8, color: rgb(0, 0, 0) });
  y -= 14;
  page.drawText(clean(input.preparedBy ? `Prepared by: ${input.preparedBy}` : 'Barangay official'), { x: M, y, size: 10, font, color: rgb(0, 0, 0) });
  y -= 13;
  page.drawText('Signature over printed name', { x: M, y, size: 8.5, font: italic, color: GRAY });

  const stamp = input.status === 'ISSUED' && input.issuedAt
    ? `Issued ${fmt(input.issuedAt)} - generated by SafeComm`
    : 'Generated by SafeComm - not yet issued to the reporter';
  page.drawText(clean(stamp), { x: M, y: 36, size: 7.5, font, color: GRAY });
  return pdf.save();
}
