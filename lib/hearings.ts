/**
 * The events a party is told about. Everything else - drafts, notes,
 * attendance, the other party's notice - stays with the officials.
 */
export const RESIDENT_EVENT_KINDS = ['scheduled', 'rescheduled', 'notice_issued', 'cancelled', 'outcome', 'request_approved', 'request_declined', 'reminder'] as const;
export type PartyRole = 'COMPLAINANT' | 'RESPONDENT';

/**
 * The message a party gets about one proceeding event, from the event's own
 * snapshot - or null for an event that is not theirs to know. A notice is
 * told only to the party it is addressed to, a request's answer only to the
 * party who asked. No official is named, and no note, attendance or other
 * party's detail is included.
 */
export function residentHearingMessage(e: { kind: string; after: unknown }, role: PartyRole = 'COMPLAINANT'): string | null {
  if (!(RESIDENT_EVENT_KINDS as readonly string[]).includes(e.kind)) return null;
  const a = (e.after ?? {}) as Record<string, unknown>;
  if (typeof a.hearingNumber !== 'number') return null;
  const what = sessionTitle(typeof a.stage === 'string' ? a.stage : 'MEDIATION', typeof a.session === 'number' ? a.session : 1);
  const when = typeof a.scheduledAt === 'string' ? formatHearingWhen(a.scheduledAt) : null;
  const venue = typeof a.venue === 'string' && a.venue ? ` at ${a.venue}` : '';
  const mine = (r: unknown) => (r ?? 'COMPLAINANT') === role;
  switch (e.kind) {
    case 'scheduled': return when ? `${what} is scheduled for ${when}${venue}. Open My Hearings & Notices for your notice.` : null;
    case 'rescheduled': return when ? `${what} has a new date: ${when}${venue}. Open My Hearings & Notices for the updated notice.` : null;
    case 'notice_issued': return a.recipientRole === role
      ? `Your ${kpFormName(typeof a.formNo === 'number' ? a.formNo : null)} for the ${what.toLowerCase()} has been issued. Open My Hearings & Notices to view, download or acknowledge it.` : null;
    // A draft the parties were never told about is not theirs to hear cancelled.
    case 'cancelled': return a.wasDraft ? null : `${what} was cancelled. The barangay will tell you if another date is set.`;
    case 'outcome': {
      const o = typeof a.outcome === 'string' && a.outcome in HEARING_OUTCOMES ? HEARING_OUTCOMES[a.outcome as HearingOutcome].resident : null;
      if (!o) return null;
      const summary = typeof a.outcomeSummary === 'string' && a.outcomeSummary ? `\n\n${a.outcomeSummary}` : '';
      return `${what} was held. ${o}${summary}`;
    }
    case 'request_approved': return mine(a.requesterRole) ? `Your request for a new date for the ${what.toLowerCase()} was approved.${when ? ` The new date is ${when}${venue}.` : ''}` : null;
    case 'request_declined': {
      if (!mine(a.requesterRole)) return null;
      const note = typeof a.reviewNote === 'string' && a.reviewNote ? ` ${a.reviewNote}` : '';
      return `Your request for a new date for the ${what.toLowerCase()} was not approved.${note}`;
    }
    case 'reminder': return when ? `Reminder: ${what.toLowerCase()} is on ${when}${venue}.` : null;
  }
  return null;
}

