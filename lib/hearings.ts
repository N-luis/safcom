/**
 * Hearing Management: the Katarungang Pambarangay proceedings on a blotter
 * dispute (Local Government Code, RA 7160 secs. 408-417; DILG Katarungang
 * Pambarangay Handbook) - the stages, what each status, outcome and notice
 * state means, who may have a proceeding at all, and what each party may read.
 *
 *   A. MEDIATION before the Punong Barangay - KP Form No. 8 (Notice of
 *      Hearing, to the complainant) and No. 9 (Summons, to the respondent);
 *   B. CONSTITUTION of the Pangkat ng Tagapagkasundo, when mediation fails -
 *      No. 10 (to both parties), and No. 11 to each chosen Pangkat member;
 *   C. CONCILIATION before the Pangkat, once constituted - No. 12 (to both);
 *   D. the outcome: settlement, no settlement, further proceedings,
 *      certification to file action - recorded, never generated by itself.
 *
 * Shared by the pages (browser) and the routes (server); no database access.
 *
 * Rules that hold everywhere:
 *   - a VAWC case under RA 9262 never enters this workflow - it stays in the
 *     VAWC desk's own (intervention, protection orders, referral, follow-up);
 *   - each proceeding is scheduled by an official, one at a time, and only
 *     when the stage before it calls for it - nothing is created in advance;
 *   - status (where a proceeding stands), outcome (what came of it) and the
 *     case's own status are three different things.
 */
